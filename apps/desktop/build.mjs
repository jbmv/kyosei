// The build: five esbuild bundles plus three copied renderer assets -- and, with
// `--pack`, the application bundle (KYO-176). Since KYO-450 the bundle carries no
// Python: KYO-443 removed the CPython runtime KYO-79 shipped inside it,
// and the app runs the `kyo` the user installed.
//
// esbuild rather than Vite/electron-vite: there is no dev server, no HMR and no
// plugin graph here, so a bundler that needs neither a config file nor a plugin
// ecosystem is the whole requirement. This script doubles as the `build` check.
//
// `--pack` lives HERE rather than in a script of its own for the same reason the
// bundles do: the pack is the build plus one more input (an Electron shell), and a
// second file would be a second place to keep the output paths, the externals and the
// asset list in agreement.

