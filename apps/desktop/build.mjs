/**
 * One subprocess. `capture` returns stdout instead of writing it to the terminal;
 * stderr is inherited either way, so a failing tool's own message is never swallowed.
 *
 * @param {string} program
 * @param {readonly string[]} args
 * @param {{ capture?: boolean, env?: NodeJS.ProcessEnv }} [options]
 * @returns {string}
 */
function run(program, args, options = {}) {
  const { capture, ...rest } = options;
  return execFileSync(program, [...args], {
    stdio: capture === true ? ["ignore", "pipe", "inherit"] : "inherit",
    encoding: "utf8",
    ...rest,
  });
}

/**
 * Every file under `dir`, as paths relative to it.
 * @param {string} dir
 * @param {string} [prefix]
 * @param {string[]} [found]
 * @returns {Promise<string[]>}
 */
async function filesUnder(dir, prefix = "", found = []) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const rel = prefix === "" ? entry.name : `${prefix}/${entry.name}`;
    if (entry.isDirectory()) await filesUnder(join(dir, entry.name), rel, found);
    else found.push(rel);
  }
  return found;
}

/** Executable by us, or a refusal naming the file. `terminal.ts` asks the same way. */
/** @param {string} path */
async function assertExecutable(path) {
  try {
    await access(path, constants.X_OK);
  } catch {
    throw new Error(`pack: ${path} is not executable`);
  }
}

/**
 * What a Python runtime in the bundle would look like: the directory the old pack
 * staged it in, an interpreter, or a `site-packages`. Matched per path segment.
 */
const PYTHON_RUNTIME_MARKS = [/^kyo-runtime$/, /^python(\d+(\.\d+)*)?(\.exe)?$/, /^site-packages$/];

/**
 * KYO-450.c1: the packed app contains no Python runtime.
 *
 * Read off the finished bundle -- every file under `Contents/Resources`, `app.asar`
 * being one file and not descended into -- rather than trusted from the absence of
 * the staging code: an `extraResource` added back, or a dependency that vendors an
 * interpreter, would ship one without anybody writing the word "runtime".
 *
 * @param {string} resources
 * @returns {Promise<number>} how many files were looked at
 */
async function assertNoPythonRuntime(resources) {
  const files = await filesUnder(resources);
  const found = files.filter((rel) =>
    rel.split("/").some((part) => PYTHON_RUNTIME_MARKS.some((mark) => mark.test(part))),
  );
  if (found.length > 0) {
    throw new Error(
      `pack: ${resources} carries a Python runtime, and this app ships none (KYO-450, ` +
        `KYO-443):\n  ${found.slice(0, 10).join("\n  ")}` +
        (found.length > 10 ? `\n  ...and ${found.length - 10} more` : "") +
        "\nThe app runs the `kyo` on the user's login PATH (`src/main/kyo.ts`).",
    );
  }
  return files.length;
}

// ------------------------------------------------ signing and notarization (KYO-386)
//
// A pack signs with a Developer ID Application identity when the keychain holds one,
// and notarizes when it is told which credential `notarytool` should use. No
// credential is in this repository or in the bundle: the identity is looked up in
// the keychain by name, and the profile is a NAME the keychain resolves -- the Apple
// ID, the app-specific password and the team never pass through this process.
//
// The second notary route (KYO-399) is an App Store Connect API key: a `.p8` file kept
// outside every repository, named by PATH together with its key id
// and issuer id. `notarytool` reads the file itself; this process never opens it,
// copies it or prints it. It exists because the keychain profile resolves only from
// the GUI login session -- from ssh or a tmux server it fails with "No Keychain
// password item found" -- and a file on disk needs no keychain.
//
// Without an identity the pack is ad-hoc exactly as before this record and says so
// in one line, because a pack on a machine that cannot sign is an ordinary pack and
// not a failure. What IS refused is a request that cannot be honoured: an identity
// named that the keychain does not hold, or a notarization asked of an ad-hoc pack.

/** Names the identity to sign with; `-` asks for ad-hoc on a machine that could sign. */
const SIGN_IDENTITY_ENV = "KYOSEI_SIGN_IDENTITY";

/** Names the `notarytool` keychain profile (`xcrun notarytool store-credentials`). */
const NOTARY_PROFILE_ENV = "KYOSEI_NOTARY_PROFILE";

/** The API-key route (KYO-399): the `.p8` file's path, its key id, and the issuer id. */
const NOTARY_KEY_ENV = "KYOSEI_NOTARY_KEY";
const NOTARY_KEY_ID_ENV = "KYOSEI_NOTARY_KEY_ID";
const NOTARY_ISSUER_ENV = "KYOSEI_NOTARY_ISSUER";
const NOTARY_KEY_VARS = [NOTARY_KEY_ENV, NOTARY_KEY_ID_ENV, NOTARY_ISSUER_ENV];

/** The certificate kind a copy moved to another Mac needs; "Apple Development" is not it. */
const DEVELOPER_ID = "Developer ID Application";

/** The main binary's and the plain helper's entitlements; see the file for why so few. */
const ENTITLEMENTS = join(root, "entitlements.mac.plist");

/**
 * @typedef {{ hash: string, name: string }} KeychainIdentity
 * @typedef {{ mode: "adhoc", reason: string }} AdhocPlan
 * @typedef {{ route: "profile", profile: string }} ProfileCredential
 * @typedef {{ route: "key", key: string, keyId: string, issuer: string }} KeyCredential
 * @typedef {ProfileCredential | KeyCredential} NotaryCredential
 * @typedef {{ mode: "signed", identity: KeychainIdentity, team: string,
 *             notary: NotaryCredential | null }} SignedPlan
 * @typedef {AdhocPlan | SignedPlan} SigningPlan
 */

/**
 * The valid code-signing identities `security find-identity` lists, parsed.
 *
 * @param {string} listing
 * @returns {KeychainIdentity[]}
 */
function parseIdentities(listing) {
  /** @type {KeychainIdentity[]} */
  const found = [];
  for (const line of listing.split("\n")) {
    const match = /^\s*\d+\)\s+([0-9A-F]{40})\s+"(.+)"\s*$/.exec(line);
    if (match?.[1] !== undefined && match[2] !== undefined) {
      found.push({ hash: match[1], name: match[2] });
    }
  }
  return found;
}

/** @param {KeychainIdentity} id */
function isDeveloperId(id) {
  return id.name.startsWith(`${DEVELOPER_ID}: `);
}

/**
 * The team a signature by `identity` carries, which is its certificate's OU -- not
 * the parenthetical in its name, which for an "Apple Development" identity is the
 * person's own id. `verifyBundle` checks every nested signature against it.
 *
 * @param {KeychainIdentity} identity
 * @returns {string}
 */
function certificateTeam(identity) {
  const pems = run("security", ["find-certificate", "-a", "-c", identity.name, "-p"], {
    capture: true,
  });
  for (const pem of pems.match(/-----BEGIN CERTIFICATE-----[^-]+-----END CERTIFICATE-----/g) ??
    []) {
    const cert = new X509Certificate(pem);
    if (cert.fingerprint.replaceAll(":", "") !== identity.hash) continue;
    const team = /^OU=(.+)$/m.exec(cert.subject)?.[1];
    if (team !== undefined) return team;
  }
  throw new Error(`pack: cannot read a team identifier off the certificate of ${identity.name}`);
}

/** @returns {KeychainIdentity[]} */
function keychainIdentities() {
  if (process.platform !== "darwin") return [];
  return parseIdentities(
    run("security", ["find-identity", "-v", "-p", "codesigning"], { capture: true }),
  );
}

/**
 * Which credential `notarytool` is handed, from the environment alone -- or null when
 * none is named and the pack does not notarize. Every refusal here happens before
 * anything is built, and before the keychain is asked anything (KYO-399.c2).
 *
 * The key file is checked to exist and nothing more: its path is what `notarytool`
 * is given, and its contents never enter this process (KYO-399.c4).
 *
 * @param {NodeJS.ProcessEnv} env
 * @returns {NotaryCredential | null}
 */
function notaryCredential(env) {
  const profile = env[NOTARY_PROFILE_ENV] ?? "";
  const set = NOTARY_KEY_VARS.filter((name) => (env[name] ?? "") !== "");
  if (set.length === 0) return profile === "" ? null : { route: "profile", profile };
  if (profile !== "") {
    throw new Error(
      `pack: ${NOTARY_PROFILE_ENV} and ${set.join(", ")} are both set, which names two ` +
        "notary routes -- the keychain profile and the App Store Connect API key -- and " +
        `a pack uses one. Unset ${NOTARY_PROFILE_ENV} to notarize with the API key, or ` +
        `unset ${set.join(", ")} to notarize with the keychain profile.`,
    );
  }
  const missing = NOTARY_KEY_VARS.filter((name) => !set.includes(name));
  if (missing.length > 0) {
    throw new Error(
      `pack: ${set.join(" and ")} ${set.length === 1 ? "is" : "are"} set and ` +
        `${missing.join(" and ")} ${missing.length === 1 ? "is" : "are"} not. Notarizing ` +
        `with an App Store Connect API key needs all three: ${NOTARY_KEY_ENV} (the path ` +
        `of the AuthKey_<KEYID>.p8 file), ${NOTARY_KEY_ID_ENV} and ${NOTARY_ISSUER_ENV}. ` +
        `Set ${missing.join(" and ")}, or unset ${set.join(" and ")} to pack without ` +
        "the API key.",
    );
  }
  const named = /** @type {string} */ (env[NOTARY_KEY_ENV]);
  const key = resolve(named);
  /** @type {import("node:fs").Stats | undefined} */
  let found;
  try {
    found = statSync(key);
  } catch {
    // reported below
  }
  if (found === undefined || !found.isFile()) {
    throw new Error(
      `pack: ${NOTARY_KEY_ENV}=${JSON.stringify(named)} names no file` +
        `${found === undefined ? "" : " (it is a directory)"}. Set ${NOTARY_KEY_ENV} to ` +
        "the path of the AuthKey_<KEYID>.p8 file App Store Connect gave you, kept " +
        "outside every repository.",
    );
  }
  return {
    route: "key",
    key,
    keyId: /** @type {string} */ (env[NOTARY_KEY_ID_ENV]),
    issuer: /** @type {string} */ (env[NOTARY_ISSUER_ENV]),
  };
}

/**
 * The arguments that tell `notarytool` which credential to use, for `submit`, `log`
 * and `history` alike. The key route passes the file's PATH; `notarytool` reads it.
 *
 * @param {NotaryCredential} credential
 * @returns {string[]}
 */
function notaryArgs(credential) {
  return credential.route === "profile"
    ? ["--keychain-profile", credential.profile]
    : ["--key", credential.key, "--key-id", credential.keyId, "--issuer", credential.issuer];
}

/**
 * The credential in words, for the plan line and the refusals -- the profile's name,
 * or the key id and the file's path, never the key's contents (KYO-399.c3).
 *
 * @param {NotaryCredential} credential
 */
function describeNotary(credential) {
  return credential.route === "profile"
    ? `the keychain profile ${JSON.stringify(credential.profile)}`
    : `the App Store Connect API key ${credential.keyId} at ${credential.key}`;
}

/** @param {string} arg */
function shellQuote(arg) {
  return /^[\w@%+=:,./-]+$/.test(arg) ? arg : `'${arg.replaceAll("'", "'\\''")}'`;
}

/**
 * The command that checks a credential without submitting anything: the one a
 * submission failure names, for whichever route the pack used (KYO-399.c3).
 *
 * @param {NotaryCredential} credential
 */
function notaryCheckCommand(credential) {
  return ["xcrun", "notarytool", "history", ...notaryArgs(credential)].map(shellQuote).join(" ");
}

/**
 * Decide how this pack is signed, from the environment and the keychain, before any
 * work is done -- so a refusal costs nothing and a pack never builds for minutes and
 * then discovers it was asked for something it cannot do.
 *
 * @param {NodeJS.ProcessEnv} env
 * @param {KeychainIdentity[]} identities
 * @returns {SigningPlan}
 */
function signingPlan(env, identities) {
  const asked = env[SIGN_IDENTITY_ENV] ?? "";
  const notary = notaryCredential(env);
  const developerIds = identities.filter(isDeveloperId);
  /** @param {KeychainIdentity[]} ids */
  const named = (ids) => ids.map((id) => JSON.stringify(id.name)).join(", ") || "none";

  /** @type {AdhocPlan | null} */
  let adhoc = null;
  /** @type {KeychainIdentity | undefined} */
  let chosen;
  if (process.platform !== "darwin") {
    adhoc = { mode: "adhoc", reason: `code signing is macOS-only and this is ${process.platform}` };
  } else if (asked === "-") {
    adhoc = { mode: "adhoc", reason: `${SIGN_IDENTITY_ENV}=- asked for it` };
  } else if (asked !== "") {
    // A name asked for may be any valid signing identity, an "Apple Development" one
    // included: a stable signature is what keeps the firewall's answer across re-packs,
    // and that needs no Developer ID. Only notarization does, and is refused below.
    chosen = identities.find((id) => id.hash === asked || id.name.includes(asked));
    if (chosen === undefined) {
      throw new Error(
        `pack: ${SIGN_IDENTITY_ENV}=${JSON.stringify(asked)} names no valid code-signing ` +
          `identity in the keychain. It holds ${named(identities)}. Name one of those, set ` +
          `${SIGN_IDENTITY_ENV}=- to pack ad-hoc, or unset it to sign with the keychain's ` +
          `only ${DEVELOPER_ID} identity.`,
      );
    }
  } else if (developerIds.length === 1) {
    chosen = developerIds[0];
  } else if (developerIds.length === 0) {
    adhoc = { mode: "adhoc", reason: `the keychain holds no ${DEVELOPER_ID} identity` };
  } else {
    throw new Error(
      `pack: the keychain holds ${developerIds.length} ${DEVELOPER_ID} identities ` +
        `(${named(developerIds)}) and nothing says which to sign with. Set ` +
        `${SIGN_IDENTITY_ENV} to one of them.`,
    );
  }

  if (adhoc !== null || (chosen !== undefined && !isDeveloperId(chosen))) {
    if (notary !== null) {
      const why =
        adhoc !== null
          ? `this pack would be ad-hoc because ${adhoc.reason}`
          : `${JSON.stringify(chosen?.name)} is not a ${DEVELOPER_ID} identity`;
      const vars = notary.route === "profile" ? NOTARY_PROFILE_ENV : NOTARY_KEY_VARS.join(", ");
      throw new Error(
        `pack: ${vars} ${notary.route === "profile" ? "asks" : "ask"} for notarization ` +
          `with ${describeNotary(notary)}, and ${why}. Apple notarizes only a bundle ` +
          `signed with a ${DEVELOPER_ID} identity: add one to the keychain (or name it in ` +
          `${SIGN_IDENTITY_ENV}), or unset ${vars}.`,
      );
    }
    if (adhoc !== null) return adhoc;
  }
  const identity = /** @type {KeychainIdentity} */ (chosen);
  return {
    mode: "signed",
    identity,
    team: certificateTeam(identity),
    notary,
  };
}

/**
 * The one line a pack prints about its signature, whichever it is.
 * @param {SigningPlan} plan
 */
function describePlan(plan) {
  if (plan.mode === "adhoc") {
    return (
      `sign    ad-hoc, because ${plan.reason}: this bundle opens on this Mac only, and a ` +
      "copy moved to another needs its quarantine removed by hand"
    );
  }
  return (
    `sign    ${plan.identity.name}, hardened runtime, secure timestamp; ` +
    (!isDeveloperId(plan.identity)
      ? `not a ${DEVELOPER_ID} identity, so this bundle cannot be notarized and a copy on ` +
        "another Mac still needs its quarantine removed"
      : plan.notary === null
        ? `not notarized (neither ${NOTARY_PROFILE_ENV} nor ${NOTARY_KEY_VARS.join("/")} is set)`
        : `notarized with ${describeNotary(plan.notary)}`)
  );
}

/** How long the preflight waits for the keychain before calling it a prompt nobody answered. */
const KEYCHAIN_WAIT_SECONDS = 120;

/**
 * Sign one throwaway file with the plan's identity, before any real work.
 *
 * When the Developer ID key has been added to the login keychain and `codesign` is
 * not on its access list, the first `codesign` of the pack opens a keychain dialog and
 * waits on it -- indefinitely, with nobody at the screen, deep inside packager, as an
 * actual pack did. `find-identity` lists an identity whether or not `codesign` may use
 * its key, so nothing earlier can tell. This moves that dialog to the first second of
 * the pack, where a human who started it is still looking, and turns a hang into a
 * refusal naming the fix.
 *
 * @param {SignedPlan} plan
 */
async function assertKeychainSigns(plan) {
  const dir = await mkdtemp(join(tmpdir(), "kyosei-sign-"));
  try {
    const probeFile = join(dir, "probe");
    await cp("/usr/bin/true", probeFile);
    const done = spawnSync(
      "codesign",
      ["--sign", plan.identity.hash, "--force", "--timestamp=none", probeFile],
      { encoding: "utf8", timeout: KEYCHAIN_WAIT_SECONDS * 1000 },
    );
    if (done.error !== undefined || done.status !== 0) {
      const waited =
        done.error !== undefined && "code" in done.error && done.error.code === "ETIMEDOUT";
      throw new Error(
        `pack: codesign could not use the private key of ${JSON.stringify(plan.identity.name)}` +
          (waited
            ? ` -- it waited ${KEYCHAIN_WAIT_SECONDS}s on a keychain dialog nobody answered. `
            : `:\n${done.stderr ?? ""}\n`) +
          "Allow it once: run `npm run pack` where you can see the screen and answer the " +
          "dialog with Always Allow (it asks for your login password), or in Keychain " +
          "Access open that identity's private key, Access Control, and add " +
          `/usr/bin/codesign. Or set ${SIGN_IDENTITY_ENV}=- to pack ad-hoc.`,
      );
    }
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

/** The four magic numbers a Mach-O file (thin or universal) starts with. */
const MACHO_MAGICS = new Set([0xfeedface, 0xfeedfacf, 0xcefaedfe, 0xcffaedfe, 0xcafebabe]);

/**
 * Is `path` a Mach-O -- the only kind of file codesign seals a signature INTO?
 * @param {string} path
 * @returns {boolean}
 */
function isMachO(path) {
  let fd;
  try {
    fd = openSync(path, "r");
    const head = Buffer.alloc(4);
    if (readSync(fd, head, 0, 4, 0) !== 4) return false;
    return MACHO_MAGICS.has(head.readUInt32BE(0));
  } catch {
    return false;
  } finally {
    if (fd !== undefined) closeSync(fd);
  }
}

/**
 * Every Mach-O under `dir`, as absolute paths, symlinks not followed.
 * @param {string} dir
 * @returns {Promise<string[]>}
 */
async function machOsUnder(dir) {
  /** @type {string[]} */
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true, recursive: true })) {
    if (!entry.isFile()) continue;
    const path = join(entry.parentPath, entry.name);
    if (isMachO(path)) found.push(path);
  }
  return found.sort();
}

/**
 * `@electron/osx-sign`'s options for a Developer ID pack.
 *
 * Until KYO-450 this also carved the bundled CPython out (Mach-O files only, with no
 * entitlements); the bundle carries no runtime now, so every code object is the
 * Electron shell's own or the pty's prebuilds.
 *
 * @param {SignedPlan} plan
 */
function osxSignOptions(plan) {
  return {
    identity: plan.identity.hash,
    // packager's default is to warn and carry on, which would hand an unsigned
    // bundle to `verifyBundle` and then to Apple. A failure to sign is a failed pack.
    continueOnError: false,
    batchCodesignCalls: true,
    // Only the app-sandbox and provisioning-profile cases use it; neither is this app.
    preAutoEntitlements: false,
    /** @param {string} file */
    optionsForFile: (file) => {
      // The Renderer, GPU and Plugin helpers keep osx-sign's per-helper defaults.
      if (/\((Renderer|GPU|Plugin)\)\.app/.test(file)) return { hardenedRuntime: true };
      return { hardenedRuntime: true, entitlements: ENTITLEMENTS };
    },
  };
}

/**
 * One subprocess, both streams captured, never throwing -- for tools like `codesign`
 * and `spctl` that answer on stderr.
 *
 * @param {string} program
 * @param {readonly string[]} args
 * @param {NodeJS.ProcessEnv} [env]
 */
function probe(program, args, env) {
  const done = spawnSync(program, [...args], { encoding: "utf8", env: env ?? process.env });
  return {
    status: done.status,
    stdout: done.stdout ?? "",
    stderr: done.stderr ?? "",
    text: `${done.stdout ?? ""}${done.stderr ?? ""}`,
  };
}

/**
 * The executable a double-click runs, and the one KYO-378's headless server runs as
 * Node with `ELECTRON_RUN_AS_NODE=1`.
 * @param {string} bundlePath
 */
function mainExecutable(bundlePath) {
  return join(bundlePath, "Contents", "MacOS", APP_NAME);
}

/**
 * Prove the bundle carries the signature the plan promised.
 *
 * `codesign --verify --deep --strict` is necessary and not sufficient: `--deep`
 * descends into nested bundles and frameworks, and a Mach-O under
 * `Contents/Resources` is not one of those -- to the outer seal it is a resource,
 * hashed like a text file, and its own signature is never looked at. Notarization
 * does look at it. So each Mach-O in `app.asar.unpacked` is asked for itself: signed
 * by this team, hardened runtime, secure timestamp.
 *
 * @param {string} bundlePath
 * @param {SigningPlan} plan
 * @returns {Promise<string>} one line saying what was checked
 */
async function assertSignature(bundlePath, plan) {
  if (process.platform !== "darwin") return "signature not checked off macOS";
  if (plan.mode === "adhoc") {
    const shown = probe("codesign", ["--display", "--verbose=2", bundlePath]);
    if (!shown.text.includes("Signature=adhoc")) {
      throw new Error(
        `pack: expected an ad-hoc signature on ${bundlePath} and codesign says:\n${shown.text}`,
      );
    }
    return "ad-hoc, as planned";
  }

  const verified = probe("codesign", ["--verify", "--deep", "--strict", "--verbose=2", bundlePath]);
  if (verified.status !== 0) {
    throw new Error(
      `pack: \`codesign --verify --deep --strict\` refuses ${bundlePath}:\n${verified.text}` +
        "A sealed resource that is missing, added or modified means something wrote into " +
        "the bundle after it was signed.",
    );
  }

  const resources = join(bundlePath, "Contents", "Resources");
  const nested = await machOsUnder(join(resources, "app.asar.unpacked"));
  /** @type {string[]} */
  const wrong = [];
  for (const file of [bundlePath, ...nested]) {
    const shown = probe("codesign", ["--display", "--verbose=4", file]);
    const own = probe("codesign", ["--verify", "--strict", file]);
    const problems = [];
    if (own.status !== 0) problems.push(own.text.trim());
    if (!shown.text.includes(`Authority=${plan.identity.name}`)) problems.push("not our identity");
    if (!shown.text.includes(`TeamIdentifier=${plan.team}`)) problems.push("not our team");
    if (!/flags=0x[0-9a-f]*\([^)]*runtime[^)]*\)/.test(shown.text)) problems.push("no runtime");
    if (!/^Timestamp=/m.test(shown.text)) problems.push("no secure timestamp");
    if (problems.length > 0)
      wrong.push(`${relative(bundlePath, file) || "."}: ${problems.join("; ")}`);
  }
  if (wrong.length > 0) {
    throw new Error(
      `pack: ${wrong.length} code object(s) in ${bundlePath} are not signed as planned ` +
        `(${plan.identity.name}, hardened runtime, secure timestamp):\n  ${wrong.join("\n  ")}\n` +
        "Notarization rejects a bundle holding any one of them. `osxSignOptions` decides " +
        "what osx-sign signs.",
    );
  }
  return `${plan.identity.name}; the bundle and ${nested.length} nested Mach-O file(s) verified`;
}

/**
 * The signed binary still runs as Node (KYO-386.c3).
 *
 * KYO-378's headless server is this executable with `ELECTRON_RUN_AS_NODE=1`, which
 * needs two things a signing change could take away: the RunAsNode fuse left on (this
 * pack flips no fuse, and a flipped one makes the variable a no-op, so the binary
 * would start a window instead) and a JIT entitlement V8 can map its code with under
 * the hardened runtime. An empty environment, as a launchd job would give it.
 *
 * @param {string} bundlePath
 * @returns {string} the Electron version the Node-mode run reported
 */
function assertRunsAsNode(bundlePath) {
  const exe = mainExecutable(bundlePath);
  const ran = probe(
    exe,
    [
      "-e",
      "process.stdout.write(JSON.stringify({ node: process.versions.node, electron: process.versions.electron, type: process.type ?? null }))",
    ],
    { ELECTRON_RUN_AS_NODE: "1" },
  );
  /** @type {{ node?: string, electron?: string, type?: string | null }} */
  let said = {};
  try {
    said = JSON.parse(ran.stdout);
  } catch {
    // reported below
  }
  if (ran.status !== 0 || said.node === undefined || said.type !== null) {
    throw new Error(
      `pack: ELECTRON_RUN_AS_NODE=1 ${exe} -e ... did not run as Node (exit ${ran.status}):\n` +
        `${ran.text}\nKYO-378's headless server starts exactly this way. A signature without ` +
        "com.apple.security.cs.allow-jit (entitlements.mac.plist) kills V8 at its first JIT " +
        "page, and a RunAsNode fuse turned off makes the variable do nothing.",
    );
  }
  return `node ${said.node}, electron ${said.electron}`;
}

/**
 * Submit the signed bundle to Apple's notary service, staple the ticket, and prove
 * Gatekeeper accepts the result (KYO-386.c2).
 *
 * `notarytool` directly rather than `@electron/notarize`: the submission id is the
 * thing a rejection is investigated by, and the log Apple keeps for it is one more
 * `notarytool` call on that id, so both are kept in `release/` next to the bundle.
 *
 * @param {string} bundlePath
 * @param {NotaryCredential} credential
 */
function notarizeBundle(bundlePath, credential) {
  const credentialArgs = notaryArgs(credential);
  // The notary service takes a zip, a dmg or a pkg, never a bare `.app`; `ditto` is
  // what keeps the bundle's symlinks and extended attributes intact in the zip.
  const zip = join(release, `${APP_NAME}-notarize.zip`);
  run("ditto", ["-c", "-k", "--keepParent", bundlePath, zip]);
  console.log(`notary  submitting ${zip} with ${describeNotary(credential)}`);
  const submitted = probe("xcrun", [
    "notarytool",
    "submit",
    zip,
    ...credentialArgs,
    "--wait",
    "--output-format",
    "json",
  ]);
  /** @type {{ id?: string, status?: string, message?: string }} */
  let answer = {};
  try {
    answer = JSON.parse(submitted.stdout);
  } catch {
    // reported below
  }
  rmSync(zip, { force: true });
  if (answer.id === undefined) {
    throw new Error(
      `pack: notarytool did not submit (exit ${submitted.status}):\n${submitted.text}` +
        `Check ${describeNotary(credential)} with \`${notaryCheckCommand(credential)}\`.`,
    );
  }
  const record = join(release, "notarization.json");
  writeFileSync(record, `${JSON.stringify(answer, null, 2)}\n`, "utf8");
  console.log(`notary  submission ${answer.id}: ${answer.status}`);
  if (answer.status !== "Accepted") {
    const log = probe("xcrun", ["notarytool", "log", answer.id, ...credentialArgs]);
    const logPath = join(release, `notary-log-${answer.id}.json`);
    writeFileSync(logPath, log.stdout || log.text, "utf8");
    throw new Error(
      `pack: Apple answered ${answer.status} to submission ${answer.id}` +
        `${answer.message === undefined ? "" : ` (${answer.message})`}. Its log, which ` +
        `names every file it refused and why, is at ${logPath}.`,
    );
  }

  run("xcrun", ["stapler", "staple", bundlePath], { capture: true });
  const assessed = probe("spctl", ["--assess", "--type", "execute", "-vv", bundlePath]);
  if (assessed.status !== 0 || !assessed.text.includes("source=Notarized Developer ID")) {
    throw new Error(
      `pack: submission ${answer.id} was accepted and stapled, and Gatekeeper still does ` +
        `not accept ${bundlePath}:\n${assessed.text}`,
    );
  }
  return { id: answer.id, assessment: assessed.text.trim().replaceAll("\n", "; ") };
}

/**
 * Re-read the built bundle and prove it satisfies the contract, rather than
 * trusting the packager's configuration to have meant what it said.
 *
 * A packaging option that silently stops doing its job -- an `unpack` glob that stops
 * matching after a dependency is renamed -- is caught here, at the pack, and not by a
 * consumer whose terminal pane has no shell in it. KYO-450 adds the other direction:
 * a Python runtime the bundle must NOT carry.
 *
 * KYO-386 adds the signature to the contract: the one `plan` promised, re-read from
 * the built bundle by `assertSignature`, and the signed main binary still running as
 * Node by `assertRunsAsNode`.
 *
 * @param {string} bundlePath
 * @param {SigningPlan} plan
 */
async function verifyBundle(bundlePath, plan) {
  const resources = join(bundlePath, "Contents", "Resources");

  // KYO-230.c1: the bundle really claims the scheme. Read back off the built plist
  // rather than trusted from the `protocols` option above, on this function's own
  // argument -- a packaging option that silently stops doing its job is exactly what
  // this re-read is for, and a deep link that lands nowhere is invisible until a human
  // clicks one. macOS only: `CFBundleURLTypes` is a plist key, and on other platforms
  // the scheme is claimed at run time or by a desktop entry nothing here writes.
  if (process.platform === "darwin") {
    const plist = await readFile(join(bundlePath, "Contents", "Info.plist"), "utf8");
    if (!plist.includes("CFBundleURLTypes") || !plist.includes(`<string>${URL_SCHEME}</string>`)) {
      throw new Error(
        `pack: ${join(bundlePath, "Contents", "Info.plist")} does not claim the ` +
          `\`${URL_SCHEME}://\` scheme, so a link clicked anywhere outside this app would ` +
          "open nothing (KYO-230.c1). The `protocols` option in this file is what writes it.",
      );
    }
  }

  // KYO-450.c1: no Python runtime anywhere in the bundle's resources.
  const looked = await assertNoPythonRuntime(resources);

  // The native pty binaries must be real files too: `@lydell/node-pty` dlopens the
  // `.node` and execs `spawn-helper`, and neither works from inside an archive.
  // `apps/desktop/README.md` named this as packaging's inheritance from KYO-124.
  const unpacked = join(resources, "app.asar.unpacked");
  const natives = (await filesUnder(unpacked)).filter(
    (path) => path.endsWith(".node") || path.endsWith("spawn-helper"),
  );
  if (natives.length === 0) {
    throw new Error(
      `pack: no native binaries under ${unpacked}. The asar \`unpack\` glob no longer ` +
        "matches @lydell/node-pty's prebuilds, so the terminal pane would have no pty.",
    );
  }
  const helper = natives.find((path) => path.endsWith("spawn-helper"));
  if (helper === undefined) throw new Error(`pack: no spawn-helper under ${unpacked}`);
  try {
    await assertExecutable(join(unpacked, helper));
  } catch {
    throw new Error(
      `pack: ${join(unpacked, helper)} is not executable, so every pty spawn would fail ` +
        "with `posix_spawnp failed` (apps/desktop/README.md, on why @lydell/node-pty was " +
        "chosen).",
    );
  }

  const signature = await assertSignature(bundlePath, plan);
  const node = process.platform === "darwin" ? assertRunsAsNode(bundlePath) : "not checked";
  return { looked, natives, signature, node };
}

async function pack() {
  // Decided first, so that a request this machine cannot honour is refused before
  // minutes of building rather than after them (KYO-386).
  const plan = signingPlan(process.env, keychainIdentities());
  console.log(describePlan(plan));
  if (plan.mode === "signed") await assertKeychainSigns(plan);

  await buildBundles();

  /** @type {Record<string, unknown>} */
  const signing = plan.mode === "signed" ? { osxSign: osxSignOptions(plan) } : {};

  // Imported here rather than at the top of the file so that `npm run build` --
  // which every check runs -- does not need the packager installed or loaded.
  const { packager } = await import("@electron/packager");
  const manifest = JSON.parse(await readFile(join(root, "package.json"), "utf8"));

  const [appPath] = await packager({
    dir: root,
    out: release,
    name: "Kyosei",
    appBundleId: "dev.kyosei.desktop",
    appVersion: manifest.version,
    overwrite: true,
    // KYO-230: `CFBundleURLTypes` in the bundle's own `Info.plist`, which is the only
    // thing that makes a `kyosei://` link clicked outside this app start it. Stated as
    // packaging configuration rather than written into a plist afterwards: a post-build
    // edit is a step somebody has to remember, and `verifyBundle` reads the finished
    // plist back either way.
    protocols: [{ name: "Kyosei deep link", schemes: [URL_SCHEME] }],
    // Only the host's platform and architecture. The record's boundary is explicit:
    // a build that runs on this machine is the whole of it, and cross-building is
    // part of the distribution question nobody has decided.
    platform: /** @type {import("@electron/packager").OfficialPlatform} */ (process.platform),
    arch: /** @type {import("@electron/packager").OfficialArch} */ (process.arch),
    asar: {
      // The pty's prebuilds are dlopened and exec'd, so they cannot live in an
      // archive. Written as the dependency's own path shape so that a rename fails
      // `verifyBundle` loudly instead of quietly shipping a pty-less terminal.
      unpack: "**/@lydell/node-pty-*/prebuilds/**",
    },
    // Sources, checks and the pack's own output do not belong in the shipped asar;
    // `dist/` is what the app runs. Paths are matched relative to `dir` with a
    // leading separator.
    ignore: [
      /^\/release($|\/)/,
      /^\/src($|\/)/,
      /^\/tests($|\/)/,
      /^\/playwright-report($|\/)/,
      /^\/test-results($|\/)/,
      /^\/(README\.md|biome\.json|tsconfig\.json|playwright\.config\.ts|build\.mjs)$/,
      /^\/entitlements\.mac\.plist$/,
    ],
    // Signing happens inside packager, before the bundle is moved into `release/`.
    // Absent for an ad-hoc pack, which is then exactly the pack this was before KYO-386.
    ...signing,
  });

  // `packager` returns the directory it wrote, which on macOS *contains* the bundle
  // rather than being it. The thing a human double-clicks is the `.app` inside.
  if (appPath === undefined) throw new Error("pack: the packager built nothing");
  const bundlePath = process.platform === "darwin" ? join(appPath, `${APP_NAME}.app`) : appPath;

  const { looked, natives, signature, node } = await verifyBundle(bundlePath, plan);

  const notarized =
    plan.mode === "signed" && plan.notary !== null ? notarizeBundle(bundlePath, plan.notary) : null;

  console.log(`\npacked  ${bundlePath}`);
  console.log(`python  none: ${looked} file(s) under Contents/Resources, no runtime (KYO-450)`);
  console.log(`unpack  ${natives.join(", ")}`);
  console.log(`signed  ${signature}`);
  console.log(`node    ELECTRON_RUN_AS_NODE=1 runs the packed binary as ${node}`);
  if (notarized !== null) {
    console.log(`notary  ${notarized.id} accepted and stapled; spctl: ${notarized.assessment}`);
  } else if (plan.mode === "signed" && isDeveloperId(plan.identity)) {
    console.log(
      `notary  not submitted: set ${NOTARY_PROFILE_ENV} to a notarytool keychain profile, ` +
        `or ${NOTARY_KEY_VARS.join(", ")} to an App Store Connect API key`,
    );
  }
  console.log(
    "\nThis bundle sits inside the checkout, where `resolveKyo` still prefers the working\n" +
      "tree (KYO-79). Copy the .app somewhere outside the repository to run it\n" +
      "on the `kyo` your login PATH has -- see apps/desktop/README.md, “Packaging”.",
  );
}

if (process.argv.includes("--pack")) await pack();
// `--sign-plan`: say how a pack would sign, from this environment and this keychain,
// and build nothing. A refusal exits non-zero with the same message a pack gives.
else if (process.argv.includes("--sign-plan")) {
  const plan = signingPlan(process.env, keychainIdentities());
  console.log(JSON.stringify({ ...plan, line: describePlan(plan) }));
}
