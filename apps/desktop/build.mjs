const MAIN_EXTERNAL = ["electron", "@lydell/node-pty"];

// ------------------------------------------------- the tab registry (KYO-232.c5)
//
// The v3 shell discovers its tab kinds from the DIRECTORIES under
// `src/renderer/tabs/`, so a stage 3 record adds a tab by adding a directory and
// edits no file anybody else is in. This is the enumeration that makes that true.
//
// A GENERATED MODULE rather than an esbuild plugin resolving a virtual import,
// because `tsc --noEmit` is a separate check in `npm run check` and knows nothing
// about esbuild's resolver: a virtual module would typecheck as missing. A real file
// on disk is seen by the bundler, the typechecker and a human reading the tree, and
// costs one `pretypecheck` hook in `package.json` to keep current.
//
// It is gitignored. It is output, and a worker who adds `tabs/record/` must get a
// diff holding their own directory and nothing else.

/** Where the generated module lands; `src/renderer/tabs/registry.ts` imports it. */
const TABS_DIR = join(src, "renderer", "tabs");
const TABS_REGISTRY = join(TABS_DIR, "registry.generated.ts");

/**
 * Every tab-kind directory: a subdirectory of `tabs/` holding an `index.ts`.
 *
 * Sorted, so the generated file is stable and a rebuild that discovered the same
 * kinds produces the same bytes. A directory with no `index.ts` is skipped rather
 * than refused -- that is a half-written tab, and failing the build of the whole app
 * over one would make the intermediate state of stage 3 work unbuildable.
 *
 * @returns {Promise<string[]>}
 */
async function tabDirectories() {
  /** @type {string[]} */
  const found = [];
  for (const entry of await readdir(TABS_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    try {
      await access(join(TABS_DIR, entry.name, "index.ts"), constants.R_OK);
    } catch {
      continue;
    }
    found.push(entry.name);
  }
  return found.sort();
}

/** Write `registry.generated.ts` from what is on disk, and return the kinds found. */
async function generateTabRegistry() {
  const kinds = await tabDirectories();
  const imports = kinds.map((kind, index) => `import kind${index} from "./${kind}/index";`);
  const entries = kinds.map(
    (kind, index) => `  { directory: ${JSON.stringify(kind)}, module: kind${index} },`,
  );
  const body = [
    "// GENERATED by build.mjs from the directories under src/renderer/tabs/.",
    "// Do not edit, and do not commit: add a DIRECTORY, run the build, and this",
    "// file follows. See src/renderer/tabs/kind.ts.",
    "",
    'import type { TabKind } from "./kind";',
    ...imports,
    "",
    "export interface DiscoveredTab {",
    "  /** The directory the module came from, which is also its kind (checked). */",
    "  directory: string;",
    "  module: TabKind;",
    "}",
    "",
    "export const DISCOVERED: DiscoveredTab[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
  await writeFile(TABS_REGISTRY, body, "utf8");
  return kinds;
}

async function buildBundles() {
  const kinds = await generateTabRegistry();
  console.log(`tabs    ${kinds.length} kind(s): ${kinds.join(", ")}`);
  await rm(dist, { recursive: true, force: true });
  await mkdir(join(dist, "renderer"), { recursive: true });
  // KYO-459: one main bundle. The headless server's (`server-main.js`, KYO-378) and the
  // build stamp it compared with the app's went with the app's server: `kyo serve` is
  // the server, and it is the CLI's.
  await build({
    ...common,
    entryPoints: [join(src, "main", "main.ts")],
    outfile: join(dist, "main", "main.js"),
    platform: "node",
    format: "cjs",
    external: MAIN_EXTERNAL,
  });

  await build({
    ...common,
    entryPoints: [join(src, "main", "preload.ts")],
    outfile: join(dist, "main", "preload.js"),
    platform: "node",
    format: "cjs",
    external: MAIN_EXTERNAL,
  });

  // The claude view's own preload (KYO-321), and its OWN bundle rather than a second
  // entry point beside the one above: the two are attached to different contents and
  // must stay different files, because the shell's preload exposes `window.kyosei` and
  // this one may expose nothing at all to the page it runs in. One output per preload
  // is what keeps "the claude view cannot be handed the shell's bridge" a property of
  // the build rather than of a line in `main.ts`.
  await build({
    ...common,
    entryPoints: [join(src, "main", "claude-preload.ts")],
    outfile: join(dist, "main", "claude-preload.js"),
    platform: "node",
    format: "cjs",
    external: MAIN_EXTERNAL,
  });

  await build({
    ...common,
    entryPoints: [join(src, "renderer", "renderer.ts")],
    outfile: join(dist, "renderer", "renderer.js"),
    platform: "browser",
    format: "iife",
    target: "chrome130",
  });

  for (const asset of ["index.html", "shell.css"]) {
    await cp(join(src, "renderer", asset), join(dist, "renderer", asset));
  }

  // xterm.js ships its stylesheet as a file rather than something importable from
  // the module graph, and the renderer's CSP allows no remote origins, so it is
  // copied beside the shell's own and linked from index.html.
  await cp(
    join(root, "node_modules", "@xterm", "xterm", "css", "xterm.css"),
    join(dist, "renderer", "xterm.css"),
  );
}

