# ------------------------------------------------ KYO-303: suggested declarations
#
# `kyo docs suggest` reads the repository and the declaration already in force and
# drafts the blocks a project MIGHT want. It writes nothing, nothing downstream depends
# on it, and the project's `documents.yml` remains the only authority — the shape
# `kyo new` has had for scope since KYO-100, where a derived value is printed under
# :data:`kyosei.registry.DERIVED_LABEL` and the stored declaration is never overridden.
#
# The design is recorded at docs/design/docs.md#kyo-303.
#
# THE ONE DESIGN RULE, and everything below follows from it: a suggestion is YAML the
# reader pastes, so a suggestion that would be REFUSED when the file is next read is
# worse than no suggestion at all. Every block this module emits is therefore run
# through the real registry validator (:func:`kyosei.registry.numbered_sections` and,
# in the tests, :func:`kyosei.registry.load_document_registry` over the pasted file)
# before it is offered, and anything that cannot be drafted validly is not offered.

#: KYO-303. What every surface calls one of these, the counterpart to
#: :data:`kyosei.registry.DERIVED_LABEL`. Named once so the command, the doctor notice
#: and the documentation cannot describe the same thing in three ways (law 3).
SUGGESTION_LABEL = "suggestion only, nothing written"

#: A document whose headings follow a numbered pattern under a set that has not declared
#: ``numbered:``.
SUGGEST_NUMBERED = "numbered-undeclared"
#: The same, with a generated index beside the document — the strongest evidence a
#: document is assembled rather than edited, and the case that can also draft ``after:``.
SUGGEST_NUMBERED_INDEXED = "numbered-index-sibling"
#: A file that says it is generated and is inside a document set's globs.
SUGGEST_GENERATED = "generated-in-globs"
#: KYO-556.c4: documents whose headings carry requirement ids (``## API-12. Title``)
#: under a set that has not declared ``ssot:``.
SUGGEST_SSOT = "ssot-id-headings"
#: KYO-562.c4: a numbered document whose history shows neither growth at its end nor
#: in-place edits — a single-commit file, say. A question to the operator, never a draft:
#: it carries no YAML, and `kyo doctor`'s notice does not count it.
SUGGEST_NUMBERED_QUESTION = "numbered-question"

#: Every kind, named here so the command, its tests and the documentation cannot list
#: different sets (law 3).
SUGGESTION_KINDS: tuple[str, ...] = (
    SUGGEST_NUMBERED,
    SUGGEST_NUMBERED_INDEXED,
    SUGGEST_GENERATED,
    SUGGEST_SSOT,
    SUGGEST_NUMBERED_QUESTION,
)

#: The name given to the set that re-declares the shipped default when a project has
#: declared nothing. See :func:`suggest` for why the default has to be re-declared at
#: all: declaring any set REPLACES :data:`kyosei.registry.DEFAULT_DOCUMENT_GLOBS`
#: outright, so a paste that named only the new set would silently stop governing the
#: README it was governing five minutes earlier.
DEFAULT_SET_NAME = "docs"

#: How many lines of a file's head are read when asking whether it says it is generated.
#: A header line, by definition, is at the top: scanning further would start matching
#: prose ABOUT generated files, of which this repository's own documents have plenty.
GENERATED_HEADER_LINES = 5

#: What a file says when it says it is generated. Deliberately the two phrasings the
#: criterion names ("generated by" / "do not edit") plus the spellings that are the same
#: sentence — a header saying "auto-generated" is not making a different claim.
_GENERATED_RE = re.compile(
    r"auto[-\s]?generated|generated by|generated from|generated file|"
    r"do not (?:hand[-\s]?)?edit|do not modify",
    re.IGNORECASE,
)

#: A backticked run inside a generated header, which is where a project usually writes
#: the command that regenerates the file ("run `make notes-index` to regenerate"). Read
#: as a candidate for ``after:`` — evidence, never a guess: a header with no backticked
#: command yields no ``after:`` and the suggestion says so.
_BACKTICKED_RE = re.compile(r"`([^`\n]+)`")

#: A heading that carries a number: the hashes, whatever literal text precedes the
#: number, the number, and one immediately following punctuation character if there is
#: one. ``## 204. APP-58: the dashboard (2026-09-16)`` yields ``("## ", "204", ".")``,
#: which is exactly the template ``"## {number}."`` the consumer hand-wrote.
_NUMBERED_HEADING_RE = re.compile(r"^(#{1,6} [^0-9\n]*)(\d+)([^0-9\s]?)")

#: How many headings must follow one template before it is a pattern rather than a
#: coincidence. Three, because two consecutive numbers happen in prose ("## 1. Install",
#: "## 2. Configure") often enough that suggesting a fragments directory over them would
#: be noise — and noise is what turns a notice into something nobody reads (KYO-33).
MIN_NUMBERED_HEADINGS = 3

#: How sparse a run of numbers may be and still read as a counter. A document numbered
#: 1..204 spans 204 for 204 headings; three headings numbered 2019, 2022 and 2026 span 8
#: for 3, and are years. The bound is generous on purpose — a document that has deleted
#: sections is still numbered — and it is the second half of what keeps dates out, the
#: first being that a repeated year is not strictly increasing at all.
MAX_NUMBER_SPREAD = 3


#: KYO-556.c4: a heading that owns a requirement id, the shape KYO-551's survey found in
#: every id-bearing spec: the hashes, an upper-case prefix, ``-``, a number, ``. `` and a
#: title. Lower-case prefixes and ids without the ``. Title`` are not read: the drafted
#: ``id_heading`` is ``'{id}. {title}'``, and a heading it would not match is no evidence
#: for it.
_ID_HEADING_RE = re.compile(r"^#{1,6} ([A-Z][A-Z0-9]*)-(\d+)\. \S")

#: How many headings of one prefix a document must carry before the prefix reads as an
#: id scheme it owns. Two, "repeated": a prefix and a number before ``. Title`` is
#: already a narrow shape, and a spec with two requirements so far is still a spec.
MIN_ID_HEADINGS = 2

#: The ``id_heading`` every ssot draft carries: the one shape :data:`_ID_HEADING_RE` reads.
SSOT_ID_HEADING = "{id}. {title}"


def infer_id_headings(text: str) -> dict[str, list[str]]:
    """Each prefix ``text``'s headings own ids under, with those ids in file order.

    Fence-aware for :func:`infer_numbering`'s reason: a document that explains the id
    scheme quotes a heading inside a fence, and that example owns nothing. Prefixes with
    fewer than :data:`MIN_ID_HEADINGS` headings are dropped.
    """
    found: dict[str, list[str]] = {}
    for line, in_code in _fenced(text.splitlines()):
        if in_code:
            continue
        match = _ID_HEADING_RE.match(line)
        if match:
            found.setdefault(match.group(1), []).append(f"{match.group(1)}-{match.group(2)}")
    return {prefix: ids for prefix, ids in found.items() if len(ids) >= MIN_ID_HEADINGS}


@dataclass(frozen=True)
class Numbering:
    """What a document's own headings say about how it is numbered (KYO-303.c1)."""

    #: The ``numbered.heading`` template inferred from the headings themselves.
    template: str
    #: Every number that follows it, in file order.
    numbers: tuple[int, ...]

    @property
    def count(self) -> int:
        return len(self.numbers)

    @property
    def last(self) -> int:
        return self.numbers[-1]


def _numbered_heading_lines(text: str) -> list[tuple[int, str, int]]:
    """``(line number from 1, template, number)`` for every numbered heading outside a
    fence — the one reading :func:`infer_numbering` and :func:`growth_evidence` share."""
    found: list[tuple[int, str, int]] = []
    for line_number, (line, in_code) in enumerate(_fenced(text.splitlines()), start=1):
        if in_code:
            continue
        match = _NUMBERED_HEADING_RE.match(line)
        if not match:
            continue
        prefix, number, suffix = match.groups()
        found.append(
            (line_number, f"{prefix}{registry_module.HEADING_NUMBER}{suffix}", int(number))
        )
    return found


def infer_numbering(text: str) -> Numbering | None:
    """The heading template ``text``'s own headings follow, or ``None``.

    Fence-aware for :func:`numbered_headings`'s reason and then some: a README that
    explains a numbered-notes format quotes one of its headings inside a fence, and
    inferring a project's numbering from an example of it would be inferring it from
    documentation about another file.

    The winning template is the one the most headings follow; ties go to the one that
    appears first, so the answer does not depend on dict ordering. The run must then be
    strictly increasing and dense (:data:`MAX_NUMBER_SPREAD`).

    That is a numbered file, and nothing more (KYO-562): a plan whose ``## 1.`` to
    ``## 12.`` are edited in place passes all of it. Whether the file is append-only —
    the only thing ``numbered:`` describes — is a question about its history, which
    :func:`growth_evidence` reads.
    """
    order: list[str] = []
    runs: dict[str, list[int]] = {}
    for _, template, number in _numbered_heading_lines(text):
        if template not in runs:
            runs[template] = []
            order.append(template)
        runs[template].append(number)
    if not order:
        return None
    template = max(order, key=lambda name: (len(runs[name]), -order.index(name)))
    numbers = runs[template]
    if len(numbers) < MIN_NUMBERED_HEADINGS:
        return None
    if any(later <= earlier for earlier, later in zip(numbers, numbers[1:], strict=False)):
        return None
    if numbers[-1] - numbers[0] + 1 > MAX_NUMBER_SPREAD * len(numbers):
        return None
    return Numbering(template=template, numbers=tuple(numbers))


#: KYO-562: how many commits must each add a numbered section at the file's end, with no
#: commit ever editing an earlier section, before the file reads as append-only. Two,
#: because one is what any numbered plan does the one time it gains a section; two
#: separate commits landing at the end is the smallest repetition, and a log has dozens.
MIN_APPEND_COMMITS = 2

#: The three answers :func:`growth_evidence` gives.
GROWS_AT_END = "grows-at-end"
EDITED_IN_PLACE = "edited-in-place"
CANNOT_TELL = "cannot-tell"


@dataclass(frozen=True)
class GrowthEvidence:
    """What a numbered file's git history says about how it grows (KYO-562).

    Each commit after the one that created the file is read against the revision it
    changed, using the numbered headings of the template the file carries today:

    * **an append** adds a numbered heading to a revision that already had one, and
      changes nothing from the first numbered heading up to the last one — so it changed
      only the preamble, the last section, or what follows it;
    * **an in-place edit** changes, removes or inserts a line anywhere from the first
      numbered heading up to the line before the last one — a section that was no longer
      the newest when the commit touched it;
    * anything else (the preamble, the newest section's own text, a rename) is neither.
    """

    #: Commits on the first-parent chain that changed the file, the creating one included.
    commits: int
    appends: int
    in_place: int
    #: The first commit that edited an earlier section, abbreviated.
    first_in_place: str | None = None
    #: ``False`` when git could not say at all (not a repository, unreadable history).
    readable: bool = True

    @property
    def verdict(self) -> str:
        if self.in_place and not self.appends:
            return EDITED_IN_PLACE
        if not self.in_place and self.appends >= MIN_APPEND_COMMITS:
            return GROWS_AT_END
        return CANNOT_TELL

    def says(self) -> str:
        """One evidence line, in the history's own numbers."""
        if not self.readable:
            return "git could not read this file's history, so nothing shows how it grows"
        if not self.commits:
            return "the file has no commits, so there is no history to show how it grows"
        counted = (
            f"{self.commits} commit(s) changed it on the first-parent chain: "
            f"{self.appends} added a numbered section at its end"
        )
        if self.in_place:
            counted += (
                f" and {self.in_place} edited a section after a later one existed "
                f"(first {self.first_in_place})"
            )
        else:
            counted += " and none edited an earlier section"
        return counted


def growth_evidence(code_root: Path, path: str, template: str) -> GrowthEvidence:
    """How ``path``'s history says it grows, judged by headings following ``template``."""
    from .docs_history import document_history

    history = document_history(code_root, path)
    if history is None:
        return GrowthEvidence(commits=0, appends=0, in_place=0, readable=False)
    appends = in_place = 0
    first_in_place: str | None = None
    for revision in history:
        if revision.before_text is None:
            continue
        before = [
            line
            for line, found, _ in _numbered_heading_lines(revision.before_text)
            if found == template
        ]
        after = [
            found
            for _, found, _ in _numbered_heading_lines(revision.after_text)
            if found == template
        ]
        earlier = (before[0], before[-1] - 1) if len(before) > 1 else None
        edited = earlier is not None and any(
            (
                hunk.old_start <= earlier[1]
                and hunk.old_start + hunk.old_count - 1 >= earlier[0]
            )
            if hunk.old_count
            else earlier[0] <= hunk.old_start <= earlier[1]
            for hunk in revision.hunks
        )
        if edited:
            in_place += 1
            first_in_place = first_in_place or revision.sha[:12]
        elif before and len(after) > len(before):
            appends += 1
    return GrowthEvidence(
        commits=len(history),
        appends=appends,
        in_place=in_place,
        first_in_place=first_in_place,
    )


def _head(path: Path, lines: int = GENERATED_HEADER_LINES) -> str:
    """The first ``lines`` lines of ``path``, or ``""`` for anything unreadable.

    Bounded because a generated INDEX is routinely a megabyte of JSON and the only
    question asked of it is what its first line claims about itself.
    """
    try:
        with path.open("r", encoding="utf-8", errors="replace") as handle:
            return "".join(next(handle, "") for _ in range(lines))
    except OSError:  # pragma: no cover - depends on a permission the tests do not set
        return ""


def generated_says(head: str) -> str | None:
    """The line in ``head`` by which a file says it is generated, or ``None``.

    The LINE, not a boolean: it is the evidence the suggestion prints, and a reader
    deciding whether to exclude a file needs to see the sentence rather than be told
    that a regular expression somewhere matched it (law 6).
    """
    for line in head.splitlines():
        if _GENERATED_RE.search(line):
            return line.strip()
    return None


def _generated_command(says: str) -> str | None:
    """The command a generated header names for regenerating itself, or ``None``."""
    found = _BACKTICKED_RE.search(says)
    if not found:
        return None
    command = found.group(1).strip()
    return command or None


@dataclass(frozen=True)
class GeneratedIndex:
    """A generated file beside a document that indexes it (KYO-303.c1's third case)."""

    path: str
    says: str
    #: What the header names as the command that regenerates it, or ``None``.
    command: str | None
    #: Which signal attributed it to the document — printed, because "this file is its
    #: index" is an inference and the reader is owed the reason.
    because: str


def _generated_index(code_root: Path, doc_path: str) -> GeneratedIndex | None:
    """A sibling of ``doc_path`` that is generated AND is about ``doc_path``.

    Two signals, either of which attributes it, and the suggestion says which fired:
    the generated header NAMES the document (a consumer project's index header reads
    "Generated by tools/generate_notes_index.py from apps/server/NOTES.md"), or the
    sibling's file name is the document's own stem plus "index".

    Siblings only — the same directory, not the tree. An index generated three
    directories away is a relationship this cannot see without guessing, and a wrong
    ``after:`` command in a suggestion is indistinguishable from a right one until it
    runs.
    """
    document = Path(doc_path)
    directory = code_root / document.parent
    if not directory.is_dir():  # pragma: no cover - the document itself is in it
        return None
    stem = document.stem.lower()
    for sibling in sorted(directory.iterdir()):
        if not sibling.is_file() or sibling.name == document.name:
            continue
        says = generated_says(_head(sibling))
        if not says:
            continue
        head = _head(sibling)
        names_it = document.name in head or document.as_posix() in head
        looks_like_index = sibling.stem.lower().startswith(stem) and "index" in sibling.stem.lower()
        if not (names_it or looks_like_index):
            continue
        return GeneratedIndex(
            path=(code_root / sibling).relative_to(code_root).as_posix(),
            says=says,
            command=_generated_command(says),
            because=(
                f"its generated header names {document.name}"
                if names_it
                else f"its name is {document.stem} plus 'index'"
            ),
        )
    return None


@dataclass(frozen=True)
class SuggestionSet:
    """One ``documents.yml`` set as the suggester sees it, declared or defaulted."""

    name: str
    globs: tuple[str, ...]
    #: The entry's other declared fields, carried into a suggested block verbatim so a
    #: block that replaces the entry cannot drop what the project already wrote.
    entry: Mapping[str, object]
    #: Does it already declare ``numbered:``? A set that does is never suggested one.
    numbered: bool
    #: Is this a real entry, or the shipped default standing in for a project that has
    #: declared nothing? The two produce differently shaped pastes — see :func:`suggest`.
    declared: bool
    #: Does it already declare ``ssot:``? A set that does is never suggested one (KYO-556).
    ssot: bool = False


def _suggestion_sets(kyosei_dir: Path) -> list[SuggestionSet]:
    """This project's document sets, or the shipped default standing in for none."""
    registry = registry_module.load_document_registry(kyosei_dir)
    found: list[SuggestionSet] = []
    for name in registry.declared_names:
        entry = registry[name]
        globs = tuple(
            glob
            for glob in (entry.get(registry_module.ENUMERATE.field_name) or ())
            if isinstance(glob, str)
        )
        # ``summary`` is a field of its own on an :class:`~kyosei.registry.Entry` and
        # the rest live in ``fields``; a block that replaces a whole set entry has to
        # carry both or the paste would drop the summary the registry requires.
        carried: dict[str, object] = {"summary": entry.summary}
        carried.update(
            {key: value for key, value in entry.fields.items() if key != "numbered"}
        )
        found.append(
            SuggestionSet(
                name=name,
                globs=globs,
                entry=carried,
                numbered=isinstance(entry.get("numbered"), dict),
                declared=True,
                ssot=isinstance(entry.get("ssot"), dict),
            )
        )
    if found:
        return found
    return [
        SuggestionSet(
            name=DEFAULT_SET_NAME,
            globs=registry_module.DEFAULT_DOCUMENT_GLOBS,
            entry={
                "summary": (
                    "Root-level markdown and the docs tree — the set Kyosei scanned "
                    "before anything was declared."
                ),
                registry_module.ENUMERATE.field_name: list(
                    registry_module.DEFAULT_DOCUMENT_GLOBS
                ),
            },
            numbered=False,
            declared=False,
        )
    ]


@dataclass(frozen=True)
class DocsSuggestion:
    """One declaration a project might want, with the evidence for it (KYO-303.c1)."""

    kind: str
    #: The ``documents.yml`` set this is about.
    set_name: str
    #: The file the evidence was read from.
    path: str
    #: One line: what is being suggested and about what.
    says: str
    #: Why — each line a fact read off the repository, never a rule of thumb.
    evidence: tuple[str, ...]
    #: The YAML to paste, as the mapping it is. Always a complete ``documents:``
    #: mapping fragment that replaces whole set entries, never a sub-key a reader has to
    #: splice at the right indentation. ``None`` for a question (KYO-562.c4), which
    #: drafts nothing.
    block: Mapping[str, object] | None
    #: What to do with :attr:`block` — the sentence printed above the YAML — or, for a
    #: question, what each answer to it means.
    how: str
    #: KYO-556: every document the block is about, when it is more than :attr:`path`.
    covers: tuple[str, ...] = ()

    @property
    def drafted(self) -> bool:
        """Is there YAML to paste? ``False`` for a question (KYO-562)."""
        return self.block is not None

    def yaml_lines(self) -> list[str]:
        """:attr:`block` as the exact lines to paste; none for a question."""
        if self.block is None:
            return []
        text = yaml.safe_dump(
            _plain(self.block), sort_keys=False, default_flow_style=False, width=100
        )
        return text.rstrip("\n").splitlines()

    def row(self) -> dict:
        """``--json``'s shape: the same facts, none of the formatting (KYO-303.c1)."""
        return {
            "kind": self.kind,
            "set": self.set_name,
            "path": self.path,
            "says": self.says,
            "evidence": list(self.evidence),
            "how": self.how,
            "yaml": "\n".join(self.yaml_lines()) + "\n" if self.drafted else None,
            "block": _plain(self.block) if self.drafted else None,
            "label": SUGGESTION_LABEL,
        }


def _plain(value: object) -> object:
    """``value`` with every mapping and sequence turned into a plain dict/list.

    ``yaml.safe_dump`` refuses a tuple and a registry entry's own mapping proxy, and
    both reach here: the entry fields are carried through verbatim from the loaded
    registry, which is the point of carrying them.
    """
    if isinstance(value, Mapping):
        return {str(key): _plain(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_plain(item) for item in value]
    return value


def _fragments_dir(doc_path: str) -> str:
    """Where this document's fragments would go, beside it and inside the repository."""
    document = Path(doc_path)
    slug = re.sub(r"[^a-z0-9]+", "-", document.stem.lower()).strip("-") or "doc"
    directory = document.parent.as_posix()
    return f"{slug}-fragments" if directory == "." else f"{directory}/{slug}-fragments"


def _set_name_for(doc_path: str, taken: set[str]) -> str:
    """A legal, unused ``documents.yml`` set name for a new set over ``doc_path``."""
    slug = re.sub(r"[^a-z0-9]+", "-", Path(doc_path).stem.lower()).strip("-")
    if not registry_module.NAME_RE.match(slug):
        slug = f"doc-{slug}".strip("-") if slug else "numbered"
    name, suffix = slug, 2
    while name in taken:
        name, suffix = f"{slug}-{suffix}", suffix + 1
    return name


def _numbered_block(
    numbering: Numbering, doc_path: str, index: GeneratedIndex | None
) -> dict | None:
    """The ``numbered:`` mapping for a document, or ``None`` if it would be REFUSED.

    The validator is the real one — :func:`kyosei.registry.numbered_sections`, the same
    function that reads the file — rather than a second opinion about what it accepts.
    This is the module's one design rule made mechanical, and the path is reachable: a
    heading whose own title contains ``{number}`` infers a template carrying the
    placeholder twice, which the registry refuses by name. Better to say nothing about
    that document than to hand someone YAML their next command rejects.
    """
    block: dict[str, object] = {
        "fragments": _fragments_dir(doc_path),
        "heading": numbering.template,
    }
    if index is not None and index.command:
        block["after"] = [index.command]
    return None if registry_module.numbered_sections(block) else block


def suggest(kyosei_dir: Path, code_root: Path) -> list[DocsSuggestion]:
    """Every declaration this repository's own files suggest, with its evidence.

    Reads ``documents.yml`` and the tree; writes nothing, opens no store and returns an
    empty list for a project with nothing to suggest — which is a real answer and is
    printed as one, not as silence (law 6).

    **Scoped to what the project already calls a document.** All three cases below are
    about files inside a declared set's globs (or, for a project that has declared none,
    inside the shipped default's). A tool that swept the whole tree looking for things
    that might be documents would be guessing at exactly the question `documents.yml`
    exists to have the project answer.

    The shape of the paste differs by whether anything is declared, and this is the trap
    the criterion's "exact YAML to paste" is really about. A project WITH sets gets a
    block that replaces one whole set entry — its own ``summary`` and ``globs`` carried
    through verbatim, so replacing it cannot drop what it already said. A project with
    NONE gets the whole ``documents:`` mapping, because declaring any set replaces the
    default outright: a paste naming only the new set would quietly stop governing the
    README that was governed a minute earlier, which is the one way a helpful suggestion
    could do real damage.
    """
    sets = _suggestion_sets(kyosei_dir)
    declared_any = any(document_set.declared for document_set in sets)
    default_entry = {} if declared_any else dict(sets[0].entry)
    taken = {document_set.name for document_set in sets}
    found: list[DocsSuggestion] = []
    for document_set in sets:
        paths = [
            path.relative_to(code_root).as_posix()
            for path in _iter_docs_files(code_root, document_set.globs)
        ]
        generated = [
            (path, says)
            for path, says in ((path, generated_says(_head(code_root / path))) for path in paths)
            if says
        ]
        if generated:
            suggestion = _generated_suggestion(document_set, paths, generated, declared_any)
            if suggestion is not None:
                found.append(suggestion)
        if document_set.numbered:
            continue
        excluded = {path for path, _ in generated}
        if not document_set.ssot:
            ssot = _ssot_suggestion(
                document_set,
                [path for path in paths if path not in excluded],
                kyosei_dir=kyosei_dir,
                code_root=code_root,
                declared_any=declared_any,
                default_entry=default_entry,
                taken=taken,
            )
            if ssot is not None:
                found.append(ssot)
                # A heading like `## API-12. Title` also reads as a numbered template
                # (`## API-{number}.`); a document drafted as an ssot set is not offered
                # numbered: too, because a set cannot be both.
                excluded |= set(ssot.covers)
        for path in paths:
            if path in excluded:
                continue
            numbering = infer_numbering(
                (code_root / path).read_text(encoding="utf-8", errors="replace")
            )
            if numbering is None:
                continue
            growth = growth_evidence(code_root, path, numbering.template)
            if growth.verdict == EDITED_IN_PLACE:
                continue
            if growth.verdict == CANNOT_TELL:
                found.append(_numbered_question(document_set, path, numbering, growth))
                continue
            index = _generated_index(code_root, path)
            suggestion = _numbered_suggestion(
                document_set,
                path,
                numbering,
                index,
                growth=growth,
                set_paths=paths,
                declared_any=declared_any,
                default_entry=default_entry,
                taken=taken,
            )
            if suggestion is not None:
                found.append(suggestion)
    return found


def _numbered_suggestion(
    document_set: SuggestionSet,
    path: str,
    numbering: Numbering,
    index: GeneratedIndex | None,
    *,
    growth: GrowthEvidence,
    set_paths: Sequence[str],
    declared_any: bool,
    default_entry: Mapping[str, object],
    taken: set[str],
) -> DocsSuggestion | None:
    """The ``numbered:`` draft for one document, validated before it is offered.

    Only for a document whose history shows it growing at its end (``growth``, KYO-562):
    numbered headings alone describe a plan edited in place just as well.

    **``numbered:`` is declared on a SET, and it applies to every file that set
    enumerates** (:func:`numbered_documents` yields one numbered document per path). So
    the draft depends on what else is in the set, and getting this wrong is not cosmetic:
    adding ``numbered:`` to a set whose globs are ``*.md`` would declare the README
    append-only and make `kyo check-branch` refuse a worker for adding a numbered
    heading to it. Three shapes, and the difference between them is exactly that:

    * the set enumerates this document ALONE — add ``numbered:`` to it, entry replaced
      whole so its own summary and globs survive the paste;
    * the set enumerates more — a NEW set over this one file, added beside it. The
      document stays in the old set too, which is harmless and is said out loud: only a
      set that declares ``numbered:`` is read for numbering, and the two enumerations
      are deduplicated by the one walk that reads them both;
    * the project declares NO sets — the whole ``documents:`` mapping, re-declaring the
      default beside the new set, because declaring any set replaces the default
      outright.
    """
    numbered = _numbered_block(numbering, path, index)
    if numbered is None:
        return None
    evidence = [
        f"{numbering.count} heading(s) in {path} follow {numbering.template!r}, "
        f"numbered {numbering.numbers[0]} through {numbering.last} in file order — "
        f"`kyo docs assemble` would give the next section {numbering.last + 1}",
        f"its history shows it growing at its end: {growth.says()}",
        f"set {document_set.name!r} declares no numbered:, so a worker adding a section "
        "here writes it into the document itself and two in one wave collide on the "
        "number, on the tail of the file and on anything generated from it",
    ]
    if index is not None:
        evidence.append(
            f"{index.path} is generated and is about this document ({index.because}): "
            f"{index.says!r}"
        )
        evidence.append(
            f"after: names {index.command!r}, read from that header — Kyosei prints it "
            "after assembly and never runs it"
            if index.command
            else "that header names no command in backticks, so no after: is drafted — "
            "add the command that regenerates the index and Kyosei will name it after "
            "assembly, never run it"
        )
    evidence.append(
        f"fragments: {numbered['fragments']} is a directory chosen beside the document "
        "and is yours to move; nothing exists there until a worker writes a fragment"
    )
    own_set = {
        "summary": f"The numbered, append-only document at {path}.",
        registry_module.ENUMERATE.field_name: [path],
        "numbered": numbered,
    }
    if document_set.declared and list(set_paths) == [path]:
        block = {"documents": {document_set.name: {**document_set.entry, "numbered": numbered}}}
        how = (
            f"replace the whole `documents.{document_set.name}:` entry in "
            f"kyosei/documents.yml with this — its summary and globs are carried through "
            "unchanged, and this document is the only file the set enumerates"
        )
    elif declared_any:
        name = _set_name_for(path, taken)
        taken.add(name)
        evidence.append(
            f"set {document_set.name!r} enumerates {len(set_paths)} file(s), and "
            "numbered: applies to EVERY file its set enumerates — so the draft is a new "
            f"set over {path} alone rather than a numbered: on {document_set.name!r}, "
            "which would declare the rest of them append-only too"
        )
        block = {"documents": {name: own_set}}
        how = (
            "add this set to the `documents:` mapping in kyosei/documents.yml beside the "
            f"ones already there — {path} stays in {document_set.name!r} as an ordinary "
            "document as well, which changes nothing: only a set declaring numbered: is "
            "read for numbering"
        )
    else:
        name = _set_name_for(path, taken)
        taken.add(name)
        block = {"documents": {DEFAULT_SET_NAME: dict(default_entry), name: own_set}}
        how = (
            "this project declares no document sets, so this is the WHOLE `documents:` "
            f"mapping for kyosei/documents.yml — the {DEFAULT_SET_NAME!r} set re-declares "
            "the default you have now, because declaring any set replaces it outright"
        )
    return DocsSuggestion(
        kind=SUGGEST_NUMBERED_INDEXED if index is not None else SUGGEST_NUMBERED,
        set_name=document_set.name,
        path=path,
        says=(
            f"{path} looks numbered and append-only, and set {document_set.name!r} does "
            "not say so"
        ),
        evidence=tuple(evidence),
        block=block,
        how=how,
    )


def _numbered_question(
    document_set: SuggestionSet, path: str, numbering: Numbering, growth: GrowthEvidence
) -> DocsSuggestion:
    """KYO-562.c4: a numbered document whose history cannot say whether it is
    append-only gets a question and no drafted set."""
    return DocsSuggestion(
        kind=SUGGEST_NUMBERED_QUESTION,
        set_name=document_set.name,
        path=path,
        says=f"{path} has numbered headings; is it an append-only log?",
        evidence=(
            f"{numbering.count} heading(s) in {path} follow {numbering.template!r}, "
            f"numbered {numbering.numbers[0]} through {numbering.last} in file order",
            growth.says(),
            f"a numbered: set is drafted only from history showing the file grow at its "
            f"end — at least {MIN_APPEND_COMMITS} commits each adding a numbered section "
            "after the last one, and none editing an earlier section — because numbered "
            "headings alone describe a plan edited in place just as well",
        ),
        block=None,
        how=(
            "nothing is drafted. If it is an append-only log, declare numbered: on its set "
            "yourself, or run `kyo docs suggest` again once its history shows it; if its "
            "sections are edited in place, there is nothing to do"
        ),
    )


def _ssot_status_block(entry: Mapping[str, object]) -> dict:
    """The ``section_status:`` an ssot draft needs: the set's own, with ``superseded``
    added to its statuses if missing, or ``{statuses: [current, superseded]}``."""
    current = entry.get("section_status")
    if not isinstance(current, Mapping):
        return {"statuses": ["current", "superseded"]}
    status = dict(_plain(current))
    statuses = [str(item) for item in status.get("statuses") or ()]
    if "superseded" not in [item.strip().lower() for item in statuses]:
        statuses.append("superseded")
    status["statuses"] = statuses
    return status


def _merged_declaration(kyosei_dir: Path, block: Mapping[str, object], declared_any: bool) -> dict:
    """The whole ``documents.yml`` a reader would have after pasting ``block``: merged
    into the declared mapping entry by entry, or the whole mapping when none is declared
    (each suggestion's ``how`` says which)."""
    path = registry_module.DOCUMENT.path_in(kyosei_dir)
    raw: dict = {}
    if path.is_file():
        loaded = yaml.safe_load(path.read_text(encoding="utf-8"))
        raw = copy.deepcopy(loaded) if isinstance(loaded, dict) else {}
    pasted = _plain(block["documents"])
    if declared_any and isinstance(raw.get("documents"), dict):
        raw["documents"].update(pasted)
    else:
        raw["documents"] = pasted
    return raw


def _draft_passes_docs_check(
    kyosei_dir: Path, code_root: Path, block: Mapping[str, object], declared_any: bool
) -> bool:
    """KYO-556.c4: does the pasted draft load, and does `kyo docs check` find nothing
    in the documents it came from that it does not find today?

    The real reader and the real check, run over a copy of the file with the draft
    pasted in, written to a temporary directory and never to the project. "Nothing it
    does not find today" rather than "nothing": a problem the project already has is
    not the draft's, and withholding a valid draft over it would hide the suggestion
    from exactly the project that has not cleaned up yet.
    """
    from . import docs_check, docs_parse

    merged = _merged_declaration(kyosei_dir, block, declared_any)
    try:
        before = docs_check.check_docs(
            code_root, documents_in=docs_parse.document_set(kyosei_dir)
        )
    except registry_module.RegistryError:
        return False
    with tempfile.TemporaryDirectory(prefix="kyo-docs-suggest-") as scratch:
        draft_dir = Path(scratch)
        registry_module.DOCUMENT.path_in(draft_dir).write_text(
            yaml.safe_dump(merged, sort_keys=False), encoding="utf-8"
        )
        try:
            drafted = docs_parse.document_set(draft_dir)
        except registry_module.RegistryError:
            return False
        after = docs_check.check_docs(code_root, documents_in=drafted)

    def found(result: docs_check.DocsCheck) -> set[str]:
        return {repr(item) for item in (*result.problems, *result.section_problems)}

    return found(after) <= found(before)


def _ssot_suggestion(
    document_set: SuggestionSet,
    paths: Sequence[str],
    *,
    kyosei_dir: Path,
    code_root: Path,
    declared_any: bool,
    default_entry: Mapping[str, object],
    taken: set[str],
) -> DocsSuggestion | None:
    """KYO-556.c4: the ``ssot:`` draft for a set's id-bearing documents, or ``None``.

    The id keys are read off the headings: ``id_heading`` is :data:`SSOT_ID_HEADING`,
    ``prefixes`` maps each prefix to the one document whose headings carry it, and
    ``id_pattern`` is exactly those prefixes, so no other ``ABC-12`` token in the
    documents (``UTF-8`` is no id anyway; another tracker's ``KYO-12`` could be) is read
    as an id. A prefix whose headings sit in two documents has no single owner and is
    left out, and said so. The three shapes are :func:`_numbered_suggestion`'s: the
    set's own entry when it enumerates exactly these documents, a new set over them
    beside it, or the whole mapping when nothing is declared.

    Offered only if the paste loads and `kyo docs check` finds nothing new in the
    documents (:func:`_draft_passes_docs_check`).
    """
    owners: dict[str, list[tuple[str, list[str]]]] = {}
    for path in paths:
        text = (code_root / path).read_text(encoding="utf-8", errors="replace")
        for prefix, ids in infer_id_headings(text).items():
            owners.setdefault(prefix, []).append((path, ids))
    prefixes = {prefix: found[0][0] for prefix, found in owners.items() if len(found) == 1}
    shared = sorted(prefix for prefix, found in owners.items() if len(found) > 1)
    if not prefixes:
        return None
    documents = [path for path in paths if path in prefixes.values()]
    ordered = dict(sorted(prefixes.items()))
    ssot = {
        "id_heading": SSOT_ID_HEADING,
        "id_pattern": "(?:" + "|".join(re.escape(prefix) for prefix in ordered) + r")-\d+",
        "prefixes": ordered,
    }
    if registry_module.ssot_block(ssot) is not None:  # pragma: no cover - derived valid
        return None
    evidence = []
    for prefix, path in ordered.items():
        ids = owners[prefix][0][1]
        evidence.append(
            f"{len(ids)} heading(s) in {path} own {prefix}- ids in the form "
            f"'## <id>. <title>' ({', '.join(ids[:3])}{', ...' if len(ids) > 3 else ''}), "
            f"and no other document's headings use {prefix}-"
        )
    for prefix in shared:
        evidence.append(
            f"{prefix}- headings appear in {len(owners[prefix])} documents "
            f"({', '.join(path for path, _ in owners[prefix])}); a prefix has one owning "
            "document, so it is left out of prefixes and id_pattern"
        )
    evidence.append(
        f"set {document_set.name!r} declares no ssot:, so nothing checks that a cited id "
        "resolves, that each id has one owning heading, or that a retired requirement "
        "stays a short tombstone"
    )
    evidence.append(
        "id_pattern names exactly these prefixes, so no other PREFIX-n token in the prose "
        "is read as an id; widen it when you add a prefix. history_lint is left at its "
        "default, warn"
    )
    evidence.append(
        "`kyo docs check` was run over the documents with this draft pasted in, and found "
        "nothing it does not find today"
    )
    status = _ssot_status_block(document_set.entry)
    if document_set.declared and list(paths) == documents:
        entry = {**document_set.entry, "section_status": status, "ssot": ssot}
        block = {"documents": {document_set.name: entry}}
        how = (
            f"replace the whole `documents.{document_set.name}:` entry in "
            "kyosei/documents.yml with this — its own fields are carried through, with "
            "section_status: (superseded included, which ssot: requires) and ssot: added"
        )
    else:
        name = _set_name_for(documents[0] if len(documents) == 1 else "specs", taken)
        own_set = {
            "summary": "Current-state requirements, each owning an id in its heading.",
            registry_module.ENUMERATE.field_name: list(documents),
            "section_status": {"statuses": ["current", "superseded"]},
            "ssot": ssot,
        }
        if declared_any:
            taken.add(name)
            evidence.append(
                f"set {document_set.name!r} enumerates {len(paths)} file(s), and ssot: "
                "applies to every file its set enumerates — so the draft is a new set over "
                f"the {len(documents)} id-bearing document(s) alone"
            )
            block = {"documents": {name: own_set}}
            how = (
                "add this set to the `documents:` mapping in kyosei/documents.yml beside "
                f"the ones already there — the documents stay in {document_set.name!r} as "
                "well, which changes nothing: only a set declaring ssot: is read for ids"
            )
        else:
            taken.add(name)
            block = {"documents": {DEFAULT_SET_NAME: dict(default_entry), name: own_set}}
            how = (
                "this project declares no document sets, so this is the WHOLE "
                f"`documents:` mapping for kyosei/documents.yml — the {DEFAULT_SET_NAME!r} "
                "set re-declares the default you have now, because declaring any set "
                "replaces it outright"
            )
    if not _draft_passes_docs_check(kyosei_dir, code_root, block, declared_any):
        return None
    return DocsSuggestion(
        kind=SUGGEST_SSOT,
        set_name=document_set.name,
        path=documents[0],
        says=(
            f"{len(documents)} document(s) in set {document_set.name!r} carry requirement "
            "ids in their headings, and the set does not declare ssot:"
        ),
        evidence=tuple(evidence),
        block=block,
        how=how,
        covers=tuple(documents),
    )


def _generated_suggestion(
    document_set: SuggestionSet,
    paths: Sequence[str],
    generated: Sequence[tuple[str, str]],
    declared_any: bool,
) -> DocsSuggestion | None:
    """The narrowing that would take generated files out of one set's globs.

    ``documents.yml`` has no exclusion field and deliberately so — "narrowing is what
    declaring a set already does" — so the only honest draft is the set re-declared over
    the files it enumerates today, less the generated ones. That is exact and it is
    *static*: a document added tomorrow is not in it. The suggestion says so rather than
    leaving the reader to discover it, and a set whose files are ALL generated yields
    nothing at all, because ``globs`` may not be empty and a set that selects no file is
    not a narrowing anybody asked for.
    """
    excluded = {path for path, _ in generated}
    keep = [path for path in paths if path not in excluded]
    if not keep:
        return None
    entry = {**document_set.entry, registry_module.ENUMERATE.field_name: keep}
    evidence = [
        f"{path} says it is generated: {says!r}" for path, says in generated
    ]
    evidence.append(
        f"it is inside set {document_set.name!r}'s globs "
        f"({', '.join(document_set.globs)}), so `kyo docs check` reads its governs: "
        "lines and `kyo docs obligations` can raise an obligation against a file whose "
        "author is a command"
    )
    evidence.append(
        f"documents.yml has no exclusion field — narrowing is what declaring a set does "
        f"— so the draft below lists the {len(keep)} file(s) the set enumerates today "
        "and is static: a document added later is not in it, and a glob you write "
        "yourself will age better"
    )
    if declared_any:
        block = {"documents": {document_set.name: entry}}
        how = (
            f"replace the whole `documents.{document_set.name}:` entry in "
            "kyosei/documents.yml with this"
        )
    else:
        block = {"documents": {DEFAULT_SET_NAME: entry}}
        how = (
            "this project declares no document sets, so this is the WHOLE `documents:` "
            "mapping for kyosei/documents.yml — it replaces the default outright, which "
            "is what excluding anything from the default requires"
        )
    return DocsSuggestion(
        kind=SUGGEST_GENERATED,
        set_name=document_set.name,
        path=generated[0][0],
        says=(
            f"{len(generated)} generated file(s) are inside set {document_set.name!r}'s "
            "globs and are suggested for exclusion"
        ),
        evidence=tuple(evidence),
        block=block,
        how=how,
    )


def suggestion_lines(found: Sequence[DocsSuggestion]) -> list[str]:
    """Every suggestion as the terminal prints it: evidence first, then the paste."""
    lines: list[str] = []
    for suggestion in found:
        lines.append(f"  [{suggestion.kind}] {suggestion.says}")
        lines += [f"      evidence: {item}" for item in suggestion.evidence]
        if not suggestion.drafted:
            lines.append(f"      {suggestion.how}")
            continue
        lines.append(f"      {suggestion.how}:")
        lines += [f"        {line}" for line in suggestion.yaml_lines()]
    return lines


