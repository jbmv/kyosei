FOUNDATION = """# Foundation

## P-1. Every answer is kept

Stored records are never deleted.

## P-2. Nothing is marked wrong without a reason

A mark cites the requirement behind it, API-1 for unknown fields.
"""

API_SPEC = """# API

## API-1. Unknown fields are rejected

Follows from P-2.

## API-2. Requests carry JSON only

```
## API-9. An example heading inside a fence owns nothing
```
"""

