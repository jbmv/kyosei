"""KYO-303: `kyo docs suggest` — drafted declarations, suggested and never enforced.

The requirement: Kyosei stays flexible about document ownership and declaration, and
offers default suggestions for it rather than enforcing them.

The shape already existed for scope. `kyo new` prints "derived (suggestion only, nothing
stored)" when a record's touches fall under a scope it did not declare, says where the
derivation came from, and stores nothing. Documents had no such surface: `documents.yml`
starts from a default pair of globs and everything after that — which files are documents
at all, which are generated, which are numbered and append-only (KYO-299's ``numbered:``)
— is hand-authored, so a consumer with a 27,000-line numbered notes file and a generated
index beside it got nothing from that block until somebody wrote it by hand.

**The one design rule every test here is really about**: a suggestion is YAML the reader
pastes, so a block the next `kyo docs check` would REFUSE is worse than no block at all.
:func:`test_every_suggested_block_is_accepted_by_the_real_reader` runs every suggestion
this module can produce through the real ``documents.yml`` reader, on the pasted file,
rather than against a second opinion about what that reader accepts.

The fixtures are the SHAPE of the consumer document that motivated the record (a
consumer project's ``apps/server/NOTES.md``: numbered ``## 204. <title> (<date>)``
headings, a ``NOTES-INDEX.md`` beside it whose first line says it is generated and names
``make notes-index``) and none of its content.
"""

