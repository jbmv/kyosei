def test_json_carries_the_same(kyo, project: Path) -> None:
    """c1: `--json` carries the same — the facts, without the formatting."""
    declare(project, UNNUMBERED)
    seed(project, index=INDEX)

    data = kyo("docs", "suggest", "--json").json

    assert data["command"] == "docs suggest"
    assert data["wrote_anything"] is False
    assert data["kinds"] == list(docs_suggest.SUGGESTION_KINDS)
    (row,) = data["suggestions"]
    assert row["kind"] == docs_suggest.SUGGEST_NUMBERED_INDEXED
    assert row["path"] == "apps/server/NOTES.md"
    assert row["label"] == docs_suggest.SUGGESTION_LABEL
    assert row["evidence"] and all(isinstance(item, str) for item in row["evidence"])
    # The structured block and the printed YAML are one fact, not two.
    assert yaml.safe_load(row["yaml"]) == row["block"]
    assert row["block"]["documents"]["notes"]["numbered"]["after"] == ["make notes-index"]


def test_with_nothing_to_suggest_it_says_so_in_one_line(kyo, project: Path) -> None:
    """c1's empty case. A real answer, printed as one — not silence (law 6)."""
    declare(project, UNNUMBERED)
    seed(project, notes="# Engineering notes\n\nNothing numbered here.\n")

    result = kyo("docs", "suggest")

    assert result.code == 0, result
    body = [line for line in result.out.splitlines() if line.strip()]
    assert len(body) == 1, body
    assert body[0].startswith("docs suggest: nothing to suggest — ")
    assert kyo("docs", "suggest", "--json").json["suggestions"] == []


def test_it_writes_nothing(kyo, project: Path) -> None:
    """c1: "and writes nothing" — checked against the tree, not against intent."""
    declare(project, UNNUMBERED)
    seed(project, index=INDEX)
    before = {
        path: path.read_bytes()
        for path in sorted(project.rglob("*"))
        if path.is_file() and "kyosei.db" not in path.name
    }

    assert kyo("docs", "suggest").code == 0

    after = {
        path: path.read_bytes()
        for path in sorted(project.rglob("*"))
        if path.is_file() and "kyosei.db" not in path.name
    }
    assert after == before


