# ------------------------------------------------------------------------ KYO-556.c3
# The documents.yml `kyo init` writes carries a commented `ssot:` example with ids and
# one without, beside the `numbered:` example, and every commented example validates.


def commented_examples(text: str) -> list[str]:
    """Each commented ``documents:`` example in ``text``, uncommented.

    An example starts at a comment line holding only ``documents:``, indented one to
    three spaces (deeper is the quoted `kyo docs suggest` output, abridged with
    ``...``), and runs while the lines are indented deeper under the same ``#``.
    """
    lines = text.splitlines()
    found = []
    for index, line in enumerate(lines):
        start = re.fullmatch(r"#( {1,3})documents:\s*", line)
        if not start:
            continue
        lead = "#" + start.group(1)
        block = ["documents:"]
        for later in lines[index + 1 :]:
            if not later.startswith(lead + "  "):
                break
            block.append(later[len(lead) :])
        found.append("\n".join(block) + "\n")
    return found


def test_the_packaged_documents_yml_shows_ssot_with_and_without_ids_and_all_validate(
    project: Path, tmp_path: Path
) -> None:
    text = (project / "kyosei" / "documents.yml").read_text(encoding="utf-8")
    examples = commented_examples(text)
    parsed = [yaml.safe_load(example)["documents"] for example in examples]
    blocks = [entry for example in parsed for entry in example.values()]
    with_ids = [entry for entry in blocks if (entry.get("ssot") or {}).get("prefixes")]
    without = [entry for entry in blocks if entry.get("ssot") == {}]
    numbered = [entry for entry in blocks if "numbered" in entry]
    assert with_ids and without and numbered, [list(entry) for entry in blocks]
    assert len(examples) >= 4  # numbered, ssot with ids, ssot without, the closing sets

    for number, example in enumerate(examples):
        directory = tmp_path / f"example-{number}"
        directory.mkdir()
        (directory / "documents.yml").write_text(example, encoding="utf-8")
        loaded = registry.load_document_registry(directory)  # raises if refused
        assert loaded.declared_names, example


