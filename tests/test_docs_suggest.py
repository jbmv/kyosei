def test_no_doctor_problem_depends_on_a_suggestion(kyo, project: Path) -> None:
    """c2's first half, and the one that matters: the problem tier never reads one."""
    declare(project, UNNUMBERED)
    seed(project, index=INDEX)

    data = kyo("doctor", "--json").json

    assert data["problems"] == []
    assert data["exit_code"] == 0 if "exit_code" in data else True
    assert doctor.CHECKS["docs_suggestions"] is doctor_registry.check_docs_suggestions
    assert "docs_suggestions" in doctor.NOTICE_CHECKS


def test_doctor_prints_at_most_one_notice_naming_the_command_and_the_count(
    kyo, project: Path
) -> None:
    """c2: one NOTICE, the command, and the count. Never one line per suggestion.

    A doctor that reproduced the drafts here would be a second rendering of the same
    data — one of the two would drift, and the noise would be paid on every Stop hook.
    """
    declare(
        project,
        {
            "documents": {
                "notes": {
                    "summary": "The engineering notes and what is generated beside them.",
                    "globs": ["apps/server/*.md"],
                }
            }
        },
    )
    seed(project, index=INDEX)
    assert len(suggestions(project)) == 2

    result = kyo("doctor")
    findings = kyo("doctor", "--json").json["checks"]["docs_suggestions"]["failures"]

    assert result.code == 0, result
    assert len(findings) == 1, findings
    assert "`kyo docs suggest` has 2 draft declaration(s)" in findings[0]
    assert "docs_suggest_notice: false" in findings[0]
    assert "[docs_suggestions]" in result.out


def test_a_project_can_turn_the_notice_off_with_one_config_line(kyo, project: Path) -> None:
    """c2: the line, and the proof that it clears the notice it names.

    A suggestion that cannot be declined is not a suggestion, and a notice that returns
    on every `kyo doctor` run from a Stop hook after the project has considered and
    declined it is the KYO-33 failure: routine noise trains people to stop reading.
    """
    declare(project, UNNUMBERED)
